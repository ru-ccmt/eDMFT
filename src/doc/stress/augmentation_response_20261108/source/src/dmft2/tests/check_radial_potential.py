#!/usr/bin/env python3
"""Check mixed-angular-momentum potential JVP/VJP against native RINT13.

The fixtures are those generated by check_lapw_radial_response.py. Only a new
scratch build directory is written; no installed executable is changed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
    p.add_argument("--fixtures", type=Path, required=True)
    p.add_argument("--work", type=Path, required=True)
    p.add_argument("--module", type=Path)
    p.add_argument("--compiler", default=shutil.which("gfortran"))
    a = p.parse_args()
    a.work.mkdir(parents=True, exist_ok=False)
    atpar = a.root / "src/dmft2/atpar"
    sources = [
        atpar / (n + ".f90")
        for n in ["outwin", "outwin_response", "lapw_radial_response", "rint13"]
    ]
    sources += [
        a.module or atpar / "lapw_radial_potential.f90",
        Path(__file__).with_name("test_radial_potential.f90"),
    ]
    build = subprocess.run(
        [
            a.compiler,
            "-O2",
            "-ffree-line-length-none",
            "-fcheck=bounds,pointer,mem,do",
            "-ffpe-trap=invalid,zero,overflow",
            *map(str, sources),
            "-o",
            str(a.work / "check"),
        ],
        cwd=a.work,
        capture_output=True,
        text=True,
    )
    (a.work / "build.log").write_text(build.stdout + build.stderr)
    build.check_returncode()
    groups = {}
    for path in sorted(a.fixtures.glob("*.input")):
        key = (
            re.sub(r"_l\d+$", "", path.stem)
            if not path.stem.startswith("synthetic")
            else "_".join(path.stem.split("_")[:2])
        )
        groups.setdefault(key, []).append(path)
    if not groups:
        raise ValueError("no native fixtures")
    rows = []
    for group in groups.values():
        for i, left in enumerate(group):
            right = group[(i + 1) % len(group)]
            run = subprocess.run(
                [str(a.work / "check"), str(left.resolve()), str(right.resolve())],
                capture_output=True,
                text=True,
            )
            (a.work / (left.stem + ".log")).write_text(run.stdout + run.stderr)
            run.check_returncode()
            values = list(map(float, run.stdout.split()))
            if len(values) != 3:
                raise ValueError("unexpected native test output")
            rows.append(
                dict(
                    left=left.stem,
                    right=right.stem,
                    central=values[0],
                    finite_difference=values[1],
                    adjoint=values[2],
                )
            )
    report = dict(
        rows=rows,
        source_sha256={
            str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in sources
        },
        maximum_errors={
            name: max(row[name] for row in rows)
            for name in ["central", "finite_difference", "adjoint"]
        },
    )
    (a.work / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(
        json.dumps(
            dict(cases=len(rows), maximum_errors=report["maximum_errors"]), indent=2
        )
    )


if __name__ == "__main__":
    main()
